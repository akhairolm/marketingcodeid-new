const buttonClass =
  'w-9 h-9 rounded-full border border-neutral-200 bg-white text-neutral-500 flex items-center justify-center transition-colors hover:text-[#FF5C28] hover:border-[#FF5C28] focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-[#FF5C28] focus-visible:ring-offset-2'

/** Share row: copy link + WhatsApp, LinkedIn, X intents. */
export function ShareActions({ url, title, className }: { url: string; title: string; className?: string }) {
  const [copied, setCopied] = useState(false)
  const encodedUrl = encodeURIComponent(url)
  const encodedTitle = encodeURIComponent(title)

  const copy = async () => {
    try {
      await navigator.clipboard.writeText(url)
      setCopied(true)
      setTimeout(() => setCopied(false), 2000)
    } catch {
      window.prompt('Salin tautan ini:', url)
    }
  }

  return (
    <div className={cn('flex items-center gap-2', className)}>
      <button
        type="button"
        onClick={copy}
        aria-label={copied ? 'Tautan tersalin' : 'Salin tautan'}
        className={cn(buttonClass, copied && 'text-emerald-600 border-emerald-300 hover:text-emerald-600 hover:border-emerald-300')}
      >
        {copied ? <Check className="w-4 h-4" /> : <Link2 className="w-4 h-4" />}
      </button>
      <a
        href={`https://wa.me/?text=${encodedTitle}%20${encodedUrl}`}
        target="_blank"
        rel="noopener noreferrer"
        aria-label="Bagikan ke WhatsApp"
        className={buttonClass}
      >
        <WhatsAppGlyph className="w-4 h-4" />
      </a>
      <a
        href={`https://www.linkedin.com/sharing/share-offsite/?url=${encodedUrl}`}
        target="_blank"
        rel="noopener noreferrer"
        aria-label="Bagikan ke LinkedIn"
        className={buttonClass}
      >
        <LinkedinGlyph className="w-3.5 h-3.5" />
      </a>
      <a
        href={`https://twitter.com/intent/tweet?text=${encodedTitle}&url=${encodedUrl}`}
        target="_blank"
        rel="noopener noreferrer"
        aria-label="Bagikan ke X"
        className={buttonClass}
      >
        <XGlyph className="w-3.5 h-3.5" />
      </a>
      <span role="status" aria-live="polite" className="sr-only">
        {copied ? 'Tautan berhasil disalin' : ''}
      </span>
    </div>
  )
}
